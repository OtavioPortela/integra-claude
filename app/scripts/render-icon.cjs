// Renderiza build/icon.svg em PNG 1024x1024 com fundo transparente (usa o próprio Electron).
const { app, BrowserWindow } = require('electron')
const fs = require('fs'); const path = require('path')
app.whenReady().then(async () => {
  const svg = fs.readFileSync(path.join(__dirname, '../build/icon.svg'), 'utf8')
  const win = new BrowserWindow({ width: 1024, height: 1024, show: false, transparent: true, frame: false, webPreferences: { offscreen: true } })
  win.webContents.setZoomFactor(1)
  await win.loadURL('data:text/html;charset=utf-8,' + encodeURIComponent(`<html><body style="margin:0;background:transparent">${svg}</body></html>`))
  await new Promise((r) => setTimeout(r, 500))
  const img = await win.webContents.capturePage({ x: 0, y: 0, width: 1024, height: 1024 })
  const out = img.getSize().width === 1024 ? img : img.resize({ width: 1024, height: 1024 })
  fs.writeFileSync(path.join(__dirname, '../build/icon.png'), out.toPNG())
  console.log('ok', img.getSize())
  app.quit()
})
